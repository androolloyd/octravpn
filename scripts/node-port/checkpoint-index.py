#!/usr/bin/env python3
"""Index the qualification checkpoints.

docs/rust-node/checkpoints/ holds one record per qualification event —
a couple of hundred JSON and Markdown files — and the only way to find one
was to read docs/rust-node/status.md, over a thousand lines of
reverse-chronological prose. This writes a table of every record: date,
file, the record's own `status` string, and the upstream commit it names.

It indexes; it does not interpret. The records have no shared schema, and
their `status` values are free text ("passed", "PASS_WITH_REQUIRED_
NEGATIVE_CONTROL", a sentence), so the column is quoted as written rather
than mapped to pass/fail.

    scripts/node-port/checkpoint-index.py            # rewrite the index
    scripts/node-port/checkpoint-index.py --check    # fail if it is stale
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
CHECKPOINTS = ROOT / "docs/rust-node/checkpoints"
INDEX = CHECKPOINTS / "README.md"
COMMIT_KEYS = ("candidate", "candidate_commit", "upstream_commit", "commit", "base_commit")


def cell(text, limit):
    text = " ".join(str(text).split()).replace("|", "\\|")
    return text if len(text) <= limit else text[: limit - 1].rstrip() + "…"


def describe(path):
    """(status, commit) for one record; blanks when it does not say."""
    if path.suffix != ".json":
        return "", ""
    try:
        record = json.loads(path.read_text(encoding="utf-8"))
    except ValueError:
        return "(not valid JSON)", ""
    if not isinstance(record, dict):
        return "", ""
    status = record.get("status", "")
    status = status if isinstance(status, str) else ""
    commit = next(
        (record[key] for key in COMMIT_KEYS if isinstance(record.get(key), str) and len(record[key]) == 40),
        "",
    )
    return status, commit[:12]


def render():
    days = sorted((d for d in CHECKPOINTS.iterdir() if d.is_dir()), reverse=True)
    records = sum(1 for day in days for f in day.iterdir() if f.is_file())
    lines = [
        "# Qualification checkpoints",
        "",
        "<!-- Generated by scripts/node-port/checkpoint-index.py; do not edit by hand. -->",
        "",
        f"{records} records across {len(days)} days, newest first. `status` is the record's",
        "own wording, quoted as written; the records share no schema, so read the",
        "record before relying on it. The current state of each launch gate is at the",
        "top of [status.md](../status.md).",
        "",
    ]
    for day in days:
        files = sorted(f for f in day.iterdir() if f.is_file())
        lines += [f"## {day.name}", "", "| Record | Status, as recorded | Upstream commit |", "| --- | --- | --- |"]
        for path in files:
            status, commit = describe(path)
            lines.append(
                f"| [{path.name}]({day.name}/{path.name}) | {cell(status, 90)} | {f'`{commit}`' if commit else ''} |"
            )
        lines.append("")
    return "\n".join(lines)


def main():
    text = render()
    if "--check" in sys.argv[1:]:
        current = INDEX.read_text(encoding="utf-8") if INDEX.exists() else ""
        if current != text:
            print(f"{INDEX.relative_to(ROOT)} is stale: run scripts/node-port/checkpoint-index.py", file=sys.stderr)
            return 1
        return 0
    INDEX.write_text(text, encoding="utf-8")
    print(f"wrote {INDEX.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())

//! Contract_vm.effort_cost shared by execution and AML effect lowering.
use super::Instruction;
impl Instruction {
    pub fn effort_cost(&self) -> i64 {
        match self.opcode() {
            0x0b | 0x0c | 0x14 | 0x16..=0x18 | 0x2a | 0x2b | 0x2d => 1,
            0x07..=0x0a | 0x19..=0x1d | 0x7b => 2,
            0x00..=0x02
            | 0x12
            | 0x13
            | 0x28
            | 0x2c
            | 0x2e
            | 0x2f
            | 0x41
            | 0x47..=0x4b
            | 0x52
            | 0x56 => 3,
            0x03..=0x06
            | 0x15
            | 0x1f
            | 0x20
            | 0x29
            | 0x42
            | 0x43
            | 0x62
            | 0x65
            | 0x68
            | 0x6a
            | 0x6e
            | 0x77
            | 0x79
            | 0x7a
            | 0x84
            | 0x85
            | 0x87
            | 0x88 => 5,
            0x7c => 8,
            0x26 | 0x40 | 0x44 | 0x61 | 0x67 | 0x69 | 0x72 | 0x73 | 0x80 | 0x83 => 10,
            0x0d | 0x10 | 0x1e | 0x45 | 0x46 | 0x63 | 0x71 | 0x76 | 0x89 => 20,
            0x66 | 0x7d | 0x7f => 25,
            0x27 | 0x59 | 0x64 | 0x6c | 0x75 | 0x7e | 0x86 => 30,
            0x0f | 0x23 | 0x3d | 0x3e | 0x4c | 0x4d | 0x51 | 0x54 | 0x58 | 0x5a | 0x6b | 0x70
            | 0x81 | 0x8a => 50,
            0x0e | 0x11 | 0x21 | 0x24 | 0x30 | 0x3b | 0x3c | 0x4e..=0x50 | 0x60 | 0x6d | 0x74 => {
                100
            }
            0x25 | 0x39 | 0x3a | 0x5d..=0x5f | 0x6f | 0x78 | 0x82 => 200,
            0x57 => 300,
            0x31 | 0x32 | 0x34 | 0x35 => 500,
            0x33 | 0x5c => 1000,
            0x55 => 2000,
            0x22 | 0x53 => 5000,
            0x5b => 10000,
            0x3f => 50000,
            0x36..=0x38 => 5_000_000,
            _ => unreachable!("all OCTB opcodes are enumerated"),
        }
    }
}
